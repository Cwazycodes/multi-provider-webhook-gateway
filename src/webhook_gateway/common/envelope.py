"""The normalised event envelope, v1: the one shape every component reads or writes."""

import json
from collections.abc import Mapping
from datetime import UTC, datetime
from enum import StrEnum
from typing import Annotated, Literal, Self

from pydantic import (
    UUID4,
    AfterValidator,
    AwareDatetime,
    BaseModel,
    ConfigDict,
    Field,
    JsonValue,
    PlainSerializer,
    StringConstraints,
    model_validator,
)


class Provider(StrEnum):
    GITHUB = "github"
    SHOPIFY = "shopify"
    STRIPE = "stripe"


class EventType(StrEnum):
    """The gateway's own event names, independent of any provider's."""

    CODE_PUSHED = "code.pushed"
    PULL_REQUEST_MERGED = "pull_request.merged"
    ORDER_CREATED = "order.created"
    ORDER_PAID = "order.paid"
    PAYMENT_SUCCEEDED = "payment.succeeded"
    PAYMENT_FAILED = "payment.failed"
    PAYMENT_REFUNDED = "payment.refunded"
    UNHANDLED = "unhandled"


def _to_utc(moment: datetime) -> datetime:
    return moment.astimezone(UTC)


def _fixed_width(moment: datetime) -> str:
    # Always microseconds and "Z", so serialised timestamps sort as the instants do.
    return moment.replace(tzinfo=None).isoformat(timespec="microseconds") + "Z"


UtcDatetime = Annotated[
    AwareDatetime,
    AfterValidator(_to_utc),
    PlainSerializer(_fixed_width, return_type=str, when_used="json"),
]
NonEmptyStr = Annotated[str, StringConstraints(min_length=1)]


class Envelope(BaseModel):
    """A verified, normalised webhook event, as ingest queues it for the processor."""

    model_config = ConfigDict(frozen=True, strict=True, extra="forbid")

    schema_version: Literal[1] = Field(description="Bumped on breaking changes.")
    event_id: UUID4 = Field(description="Generated by the gateway at ingest.")
    idempotency_key: NonEmptyStr = Field(description="'<provider>:<provider_event_id>'.")
    provider: Provider
    provider_event_id: NonEmptyStr = Field(description="The provider's own ID for the event.")
    event_type: EventType
    subject_id: NonEmptyStr = Field(description="What the event is about: '<provider>:<id>'.")
    occurred_at: UtcDatetime = Field(description="When it happened, from the payload.")
    received_at: UtcDatetime = Field(description="When ingest accepted the request.")
    correlation_id: NonEmptyStr = Field(description="The API Gateway request ID.")
    data: Mapping[str, JsonValue] = Field(description="The normalised fields for this event.")

    @model_validator(mode="after")
    def _ids_name_the_provider(self) -> Self:
        if self.idempotency_key != f"{self.provider}:{self.provider_event_id}":
            raise ValueError("idempotency_key must be '<provider>:<provider_event_id>'")
        if not self.subject_id.startswith(f"{self.provider}:"):
            raise ValueError("subject_id must start with '<provider>:'")
        return self


def envelope_json_schema() -> str:
    """The exact text of schemas/envelope.v1.json, which `make schema` writes."""
    schema = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        **Envelope.model_json_schema(),
    }
    return json.dumps(schema, indent=2, sort_keys=True) + "\n"
